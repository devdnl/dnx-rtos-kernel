_Static_assert(sizeof(_drvset_header_t) == 72, "drvset: header size changed, update _DRVSET_HEADER_VERSION");
#endif

/* number of vector table entries that can be interrupts (kernel/kvectors.h) */
#define IRQ_MAX     (256 - _KVECTOR_IRQ0)

