#define FLASH_START ((uintptr_t)__OS_DRVSET_FLASH_ADDRESS__)
#define FLASH_END   (FLASH_START + (uintptr_t)__OS_DRVSET_FLASH_SIZE__ * 1024)
#define RAM_SIZE    ((size_t)__OS_DRVSET_RAM_SIZE__ * 1024)

/* header is a part of binary interface of drvset partition */
