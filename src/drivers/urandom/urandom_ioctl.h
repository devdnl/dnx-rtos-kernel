/**
@defgroup drv-urandom URANDOM Driver

\section drv-urandom-desc Description
Driver of random number generator (equivalent of Linux /dev/urandom). Output
is generated by ChaCha20 stream cipher with fast key erasure (key is replaced
after each read, so earlier output cannot be recovered from generator state).
The key is seeded and, on each read, reseeded from entropy source of the
microcontroller:
\li STM32F2/F4/F7/H7 with RNG peripheral: hardware true random generator.
    RNG needs 48 MHz clock (F4/F7: PLLQ or PLLSAI configured by CLK driver,
    H7: HSI48 is enabled by the driver when it is RNG clock source),
\li RP2040: ring oscillator random bit (oversampled),
\li POSIX simulator: host random generator (getrandom()),
\li STM32F1/F3 and STM32F4 without RNG: weak source only (unique device ID,
    timers). Output is unpredictable only after writing secret random data
    to the device (e.g. seed file saved at previous run, see @ref drv-urandom-ddesc-write).

Read never blocks. Output is suitable for keys, salts, nonces and passwords.

\section drv-urandom-sup-arch Supported architectures
\li stm32f1, stm32f3, stm32f4, stm32f7, stm32h7 (hardware source if RNG exists)
\li rpcm0
\li posix

\section drv-urandom-ddesc Details
\subsection drv-urandom-ddesc-num Meaning of major and minor numbers
Major number selects device instance (each instance has own generator state),
minor number must be 0.

\subsubsection drv-urandom-ddesc-numres Numeration restrictions
Minor number must be 0.

\subsection drv-urandom-ddesc-init Driver initialization
To initialize driver the following code can be used:

@code
driver_init("URANDOM", 0, 0, "/dev/urandom");
@endcode

\subsection drv-urandom-ddesc-release Driver release
To release driver the following code can be used:
@code
driver_release("URANDOM", 0, 0);
@endcode

\subsection drv-urandom-ddesc-cfg Driver configuration
No configuration.

\subsection drv-urandom-ddesc-write Data write
Written data are mixed into generator state (as in Linux, no entropy is
credited). Use it to add secret random data on devices without hardware
source, e.g. seed file at system start:

@code
// start: mix seed of previous run and replace it with new one
FILE *rnd  = fopen("/dev/urandom", "r+");
FILE *seed = fopen("/etc/random-seed", "r+");
u8_t buf[32];
if (fread(buf, 1, sizeof(buf), seed) == sizeof(buf)) {
        fwrite(buf, 1, sizeof(buf), rnd);
}
fread(buf, 1, sizeof(buf), rnd);
rewind(seed);
fwrite(buf, 1, sizeof(buf), seed);
@endcode

\subsection drv-urandom-ddesc-read Data read
Device returns requested number of random bytes. Programs can use libc
function getentropy() (up to 256 bytes) that reads /dev/urandom.

@{
*/

