/**
 *  @brief  Get kind of entropy source.
 *  @param  [RD] @ref URANDOM_source_t*
 *  @return On success 0 is returned, otherwise -1.
 *  @b Example
 *  @code
    #include <sys/ioctl.h>

    //...

    URANDOM_source_t src;
    if ((ioctl(fileno(urnd), IOCTL_URANDOM__GET_SOURCE, &src) == 0) && (src == URANDOM_SOURCE__WEAK)) {
            puts("Warning: no hardware entropy source!");
    }

    //...
    @endcode
 */
#define IOCTL_URANDOM__GET_SOURCE _IOR(URANDOM, 0x02, URANDOM_source_t *)

/*==============================================================================
  Exported object types
==============================================================================*/
/**
 * Kind of entropy source.
 */
typedef enum {
        URANDOM_SOURCE__WEAK,     /*!< No hardware noise source (device ID, timers, written data).*/
        URANDOM_SOURCE__HARDWARE, /*!< Hardware noise source.*/
} URANDOM_source_t;

